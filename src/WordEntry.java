//> [ไฟล์นี้ทำอะไร] คำศัพท์ 1 คำ + คำใบ้ และตัวแยก 'ช่องตัวอักษร'
//> ใช้ทั้ง Server (สร้าง pattern, ตรวจคำตอบ) และ Client (GamePanel ใช้ slots() แยกคำเฉลย ให้ได้จำนวนช่องเท่ากับ Server)
//> จุดสำคัญ: ภาษาไทย 1 'ช่อง' ไม่เท่ากับ 1 char เสมอไป เพราะสระบน/ล่าง วรรณยุกต์ เป็น char แยก
import java.util.ArrayList;

/** คำศัพท์ 1 คำ พร้อมคำใบ้ */
public class WordEntry {
    // สระบน/ล่างและวรรณยุกต์ภาษาไทย (ไม่ใช่ตัวอักษรที่นับเป็น "ช่อง" ของตัวเอง)
    //> MARKS = อักขระที่ 'ห้อยอยู่กับพยัญชนะตัวก่อนหน้า' ได้แก่ สระบน/ล่าง (อั อิ อี อึ อื อุ อู) ไม้ไต่คู้ วรรณยุกต์ และการันต์
    //> ตัวพวกนี้ไม่นับเป็นช่องของตัวเอง แต่จะไปต่อท้ายช่องก่อนหน้า
    //> สระ า ะ ำ และสระหน้า เ แ โ ไ ใ ไม่อยู่ในนี้ จึงได้ช่องของตัวเอง
    private static final String MARKS = "ัิีึืุู็่้๊๋์ํ";

    //> word = คำตอบจริง เช่น "ค้างคาว"
    private String word;
    //> hint = คำใบ้ที่โชว์ให้ผู้เล่นดู
    private String hint;

    //> Constructor: WordBank.add() เป็นคนเรียกตอนใส่คำเข้าคลัง
    public WordEntry(String word, String hint) {
        this.word = word;
        this.hint = hint;
    }

    //> Getter: getWord() ใช้ตรวจคำตอบและส่งเฉลย / getHint() ใช้ส่งคำใบ้ไป Client
    public String getWord() { return word; }
    public String getHint() { return hint; }

    /**
     * แยกคำเป็นช่องตัวอักษร เช่น "ค้างคาว" -> [ค้, า, ง, ค, า, ว]
     * ถ้าเจอสระบน/ล่างหรือวรรณยุกต์ ให้ต่อท้ายช่องก่อนหน้า (ไม่เปิดช่องใหม่)
     */
    //> slots() แยกคำเป็นช่อง ตัวอย่าง "ค้างคาว" (7 char) -> [ ค้ , า , ง , ค , า , ว ] = 6 ช่อง
    //> ผลลัพธ์นี้ใช้ 2 อย่าง: 1) จำนวนกล่องบนจอ  2) pattern ที่ส่งไป Client เช่น "_,_,า,_,_,_"
    public ArrayList<String> slots() {
        //> result = ลิสต์ของช่อง เริ่มจากว่าง
        ArrayList<String> result = new ArrayList<>();
        //> วนทีละตัวอักษรของคำ (i = ตำแหน่ง 0 ถึง ความยาว-1)
        for (int i = 0; i < word.length(); i++) {
            //> c = ตัวอักษรตำแหน่งที่ i
            char c = word.charAt(i);
            //> เงื่อนไข 2 ข้อพร้อมกัน (&&):
            //>  1) c อยู่ใน MARKS ไหม  (indexOf คืน >= 0 ถ้าเจอ, คืน -1 ถ้าไม่เจอ)
            //>  2) มีช่องก่อนหน้าให้ต่อท้ายแล้ว (result.size() > 0)
            if (MARKS.indexOf(c) >= 0 && result.size() > 0) {
                //> last = ตำแหน่งของช่องสุดท้ายในลิสต์
                int last = result.size() - 1;
                //> result.set(ตำแหน่ง, ค่าใหม่) = แทนที่ช่องสุดท้ายด้วย 'ช่องเดิม + c'
                //> เช่น "ค" + (ไม้โท) = "ค้"  ติดกันเป็นช่องเดียว
                result.set(last, result.get(last) + c);
            } else {
                //> ไม่ใช่เครื่องหมายติดพยัญชนะ -> เปิดช่องใหม่  ("" + c = แปลง char ให้เป็น String)
                result.add("" + c);
            }
        }
        //> คืนลิสต์ช่อง ใช้ใน GameRoom (สร้าง pattern) และ GamePanel (ตอนเฉลยรอบ)
        return result;
    }
}
